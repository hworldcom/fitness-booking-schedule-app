begin;
create extension if not exists pgtap with schema extensions;
set local search_path=extensions,public;
select plan(14);
select has_table('app','coach_external_clients','external clients are separate records');
select has_table('app','coach_client_invitations','explicit targeted offers are retained');
select col_is_null('app','coach_private_bookings','client_profile_id','registered participant may be absent only for an external record');
select has_column('app','coach_private_bookings','external_client_id','canonical booking retains external reference');
select ok((select relrowsecurity and relforcerowsecurity from pg_class where oid='app.coach_external_clients'::regclass),'external records force RLS');
select ok((select relrowsecurity and relforcerowsecurity from pg_class where oid='app.coach_invitation_emails'::regclass),'delivery queue forces RLS');
select ok(not has_table_privilege('app_runtime','app.coach_external_clients','select'),'runtime cannot read raw contacts');
select ok(not has_table_privilege('app_runtime','app.coach_client_invitations','select'),'runtime cannot read raw recipient/consent rows');
select ok(not has_table_privilege('app_notification_worker','app.coach_invitation_emails','select'),'worker cannot read raw token rows');
select ok(not has_function_privilege('app_runtime','app.associate_invited_sessions(uuid)','execute'),'association hook is private');
select ok(not has_function_privilege('app_runtime','app.invitation_recipient_matches(text)','execute'),'Auth email helper is private');
select ok(has_function_privilege('app_runtime','app.external_clients(text,jsonb)','execute'),'runtime uses guarded contact command');
select ok(has_function_privilege('app_notification_worker','app.claim_coach_invitation_emails(uuid)','execute'),'worker can claim bounded delivery work');
select ok(not has_function_privilege('app_runtime','app.claim_coach_invitation_emails(uuid)','execute'),'ordinary app cannot claim arbitrary mail');
select * from finish();
rollback;
